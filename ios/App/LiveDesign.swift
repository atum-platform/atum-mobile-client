import SwiftUI
import AtumDesign

/// Production-only projection of the committed Atum design bundle. It reads no
/// prototype catalog, fixture account or synthetic screen state.
@MainActor
final class LiveDesign {
    struct RGBA: Decodable {
        let red: Double
        let green: Double
        let blue: Double
        let alpha: Double
        var color: Color { Color(.sRGB, red: red, green: green, blue: blue, opacity: alpha) }
    }
    struct Palette: Decodable {
        let light: [String: RGBA]
        let dark: [String: RGBA]
        let radii: [String: Double]
    }
    struct Glyphs: Decodable { let aliases: [String: String] }
    struct Eclipse: Decodable { let svg: String; let viewBox: [Double] }

    let copy: AtumCopy
    /// Atum Kit 0.1 (`atum-kit-tokens.json`): the roles every surface draws with.
    let kit: AtumKit
    let palette: Palette
    let glyphs: Glyphs
    let eclipse: Eclipse
    let locale: String

    init() throws {
        copy = try AtumCopy()
        kit = try AtumKit.vendored()
        let decoder = JSONDecoder()
        palette = try decoder.decode(Palette.self, from: AtumDesign.data(for: "phone-design.json"))
        glyphs = try decoder.decode(Glyphs.self, from: AtumDesign.data(for: "glyphs.json"))
        eclipse = try decoder.decode(Eclipse.self, from: AtumDesign.data(for: "marks/eclipse.json"))
        locale = Self.selectedLocale(from: copy.locales)
        PeopleNameWords.configure(unnamed: text("src.matrix.conversation-copy.copies.unnamed"),
                                  untitledChat: text("desktop.atum.roster.untitledChat"))
    }

    func text(_ key: String, arguments: [AtumCopy.Argument] = []) -> String {
        do { return try copy.text(key, locale: locale, arguments: arguments) }
        catch { preconditionFailure("Invalid production copy key: \(key)") }
    }

    /// A phrase whose arguments arrive as words, as the pending tables take
    /// them: each word becomes a number where the export declares one (desktop
    /// `count`/`day` parameters), else text. A pin that turns a pending string
    /// argument into a number then keeps working (wave 3: `inviteLinkUsage`,
    /// `routineQuotaReached`, `routineMonthlyWords`).
    func text(_ key: String, words: [String]) -> String {
        let kinds = copy.parameterKinds(key) ?? []
        let arguments: [AtumCopy.Argument] = words.enumerated().map { index, word in
            if kinds.indices.contains(index), kinds[index] == "number", let number = Int64(word) {
                return .number(number)
            }
            return .text(word)
        }
        return text(key, arguments: arguments)
    }

    /// The Kit's Phosphor icon for an exported glyph alias, as the asset name
    /// of its custom symbol (`Assets.xcassets/Phosphor`, generated by
    /// `scripts/generate-phosphor-symbols.py`). Draw it with `Image(_:)` or
    /// `Label(_:image:)`; `Image(systemName:)` would find nothing.
    func symbol(_ alias: String) -> String {
        Self.phosphorSymbol(alias)
    }

    nonisolated static func phosphorSymbol(_ alias: String) -> String {
        guard let symbol = PhosphorSymbols.aliases[alias] else {
            preconditionFailure("Missing Phosphor symbol for glyph alias: \(alias)")
        }
        return symbol
    }

    /// A legacy `phone-design.json` role resolves to its Atum Kit token
    /// (`AtumKitLegacyRoles`), so every pre-Kit surface draws with Kit colours.
    /// Roles the Kit does not name (media viewer, scrims) keep their export.
    func color(_ role: String, scheme: ColorScheme) -> Color {
        if let kitRole = AtumKitLegacyRoles.kitRole(for: role) {
            return kit.color(kitRole, scheme: scheme)
        }
        guard let value = (scheme == .dark ? palette.dark : palette.light)[role] else {
            preconditionFailure("Missing production palette role: \(role)")
        }
        return value.color
    }

    private static func selectedLocale(from supported: Set<String>) -> String {
        LiveDesignLocaleSelection.selectedLocale(preferredLanguages: Locale.preferredLanguages,
                                                 supported: supported)
    }
}

/// Maps the device's preferred-language identifiers onto the pinned
/// `AtumCopy` locales. Simplified Chinese is `zh` in the export manifest, so
/// `zh-Hans`/`zh-CN` must be negotiated to `zh` rather than passed through as
/// unsupported identifiers. Traditional Chinese stays `zh-Hant`.
enum LiveDesignLocaleSelection {
    static func selectedLocale(preferredLanguages: [String], supported: Set<String>) -> String {
        for identifier in preferredLanguages {
            let normalized = normalized(identifier)
            if supported.contains(normalized) { return normalized }
        }
        return supported.contains("vi") ? "vi" : "en"
    }

    static func normalized(_ identifier: String) -> String {
        let value = identifier.lowercased()
        if value.hasPrefix("zh-hant") { return "zh-Hant" }
        if value.hasPrefix("zh-hans") || value.hasPrefix("zh-cn") || value == "zh" { return "zh" }
        if value.hasPrefix("vi") { return "vi" }
        if value.hasPrefix("ja") { return "ja" }
        return "en"
    }
}

struct LiveGlass: ViewModifier {
    let design: LiveDesign
    let radius: Double
    @Environment(\.colorScheme) private var scheme
    @Environment(\.accessibilityReduceTransparency) private var opaque
    @Environment(\.colorSchemeContrast) private var contrast

    func body(content: Content) -> some View {
        if opaque || contrast == .increased {
            content.background(design.color("glassOpaque", scheme: scheme),
                               in: RoundedRectangle(cornerRadius: radius))
        } else {
            content.glassEffect(.regular.interactive(), in: RoundedRectangle(cornerRadius: radius))
        }
    }
}

struct LiveEclipseMark: View {
    let design: LiveDesign

    var body: some View {
        Canvas { context, size in
            let svg = design.eclipse.svg
            let attributes = try! NSRegularExpression(pattern: "([\\w-]+)=\"([^\"]+)\"")
            func values(_ tag: String) -> [String: String] {
                Dictionary(uniqueKeysWithValues: attributes.matches(in: tag,
                    range: NSRange(tag.startIndex..., in: tag)).map {
                    (String(tag[Range($0.range(at: 1), in: tag)!]),
                     String(tag[Range($0.range(at: 2), in: tag)!]))
                })
            }
            func sourceColor(_ hex: String) -> Color {
                let number = UInt32(hex.dropFirst(), radix: 16)!
                return Color(.sRGB,
                             red: Double((number >> 16) & 255) / 255,
                             green: Double((number >> 8) & 255) / 255,
                             blue: Double(number & 255) / 255,
                             opacity: 1)
            }
            let circles = try! NSRegularExpression(pattern: "<circle\\s+[^>]+>")
            let stops = try! NSRegularExpression(pattern: "<stop\\s+[^>]+>")
            let gradient = Gradient(stops: stops.matches(in: svg,
                range: NSRange(svg.startIndex..., in: svg)).map {
                let value = values(String(svg[Range($0.range, in: svg)!]))
                return .init(color: sourceColor(value["stop-color"]!)
                    .opacity(Double(value["stop-opacity"]!)!),
                    location: Double(value["offset"]!.dropLast())! / 100)
            })
            context.scaleBy(x: size.width / design.eclipse.viewBox[2],
                            y: size.height / design.eclipse.viewBox[3])
            for match in circles.matches(in: svg, range: NSRange(svg.startIndex..., in: svg)) {
                let value = values(String(svg[Range(match.range, in: svg)!]))
                let x = Double(value["cx"]!)!
                let y = Double(value["cy"]!)!
                let r = Double(value["r"]!)!
                let path = Path(ellipseIn: CGRect(x: x - r, y: y - r,
                                                  width: r * 2, height: r * 2))
                let shading: GraphicsContext.Shading = value["fill"]!.hasPrefix("#")
                    ? .color(sourceColor(value["fill"]!))
                    : .radialGradient(gradient, center: CGPoint(x: x, y: y),
                                      startRadius: 0, endRadius: r)
                context.fill(path, with: shading)
            }
        }
        .accessibilityHidden(true)
    }
}
