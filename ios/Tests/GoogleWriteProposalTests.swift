    func testAssistantEmailAndWorkCalendarWithPlatformDigests() throws {
        // Digests generated by desktop's canonicalJson, including decomposed Unicode,
        // an escaped separator, quotes, and the forwarded boolean and attachment size.
        let decoded = try Fixture.decode([
            Fixture.row(1, draft: Fixture.email, digest: Fixture.emailDigest),
