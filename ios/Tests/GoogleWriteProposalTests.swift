            await until { api.decisionContinuation != nil }
            api.proposals = []
            await store.refresh()
            XCTAssertEqual(store.cards.first?.state, .deciding(.approve))

            api.finishDecision(result)
            await caller.value
            XCTAssertEqual(store.cards.first?.state, expected)
            XCTAssertFalse(store.cards.first?.canDecide ?? true)
        }
    }

    func testOutcomeMappingAndRetry() async throws {
        let cases: [(GoogleWriteDecisionResult, GoogleWriteDecision, Bool, GoogleWriteProposalState)] = [
            (.accepted, .decline, false, .declined),
            (.refused, .approve, false, .closed),
            (.refused, .approve, true, .expired),
            (.changed, .approve, true, .changed),
            (.unavailable, .approve, false, .failedRetryable)
        ]
        for (result, action, work, expected) in cases {
            let store = GoogleWriteProposalStore()
            let api = ProposalAPI()
            api.proposals = [try Fixture.proposal(1, work: work)]
            api.result = result
            store.bind(accountID: "owner-a", api: api)
            await store.refresh()
            let card = try XCTUnwrap(store.cards.first)
            await store.decide(action, cardID: card.id)
            XCTAssertEqual(store.cards.first?.state, expected)
            XCTAssertEqual(store.cards.first?.canDecide, result == .unavailable)
            if result == .unavailable {
                api.result = .accepted
                await store.decide(action, cardID: card.id)
                XCTAssertEqual(store.cards.first?.state, .approved)
                XCTAssertEqual(api.decisions.count, 2)
            }
        }
    }

    func testRefreshFailureAndListReconciliationKeepOnlySafeDecisions() async throws {
        let store = GoogleWriteProposalStore()
        let api = ProposalAPI()
        api.proposals = [try Fixture.proposal(1), try Fixture.proposal(2, work: true),
                         try Fixture.proposal(3, digest: String(repeating: "e", count: 64))]
        store.bind(accountID: "owner-a", api: api)
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.pending, .pending, .changed])
        let changed = try XCTUnwrap(store.cards.last)
        await store.decide(.approve, cardID: changed.id)
        XCTAssertTrue(api.decisions.isEmpty)

        api.failRead = true
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.pending, .pending, .changed])
        api.failRead = false
        api.proposals = [try Fixture.proposal(4)]
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.superseded, .expired, .superseded, .pending])
        api.proposals = []
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.superseded, .expired, .superseded, .closed])
    }

    private func until(_ predicate: () async -> Bool, file: StaticString = #filePath, line: UInt = #line) async {
        for _ in 0..<200 {
            if await predicate() { return }
            try? await Task.sleep(for: .milliseconds(5))
        }
        XCTFail("Expected proposal activity did not occur", file: file, line: line)
    }
}

@MainActor private final class ProposalAPI: GoogleWriteProposalAPI {
    var reads = 0
    var proposals = [GoogleWriteProposal]()
    var failRead = false
    var holdRead = false
    var readContinuation: CheckedContinuation<[GoogleWriteProposal], Never>?
    var lastReadGate: NativeDispatchGate?
    var lastDecisionGate: NativeDispatchGate?
    var holdDecision = false
    var decisions: [(GoogleWriteDecision, String)] = []
    var result = GoogleWriteDecisionResult.accepted
    var decisionContinuation: CheckedContinuation<GoogleWriteDecisionResult, Never>?
    var decisionWasCancelled = false

    func googleWriteProposals(isCurrent: @escaping NativeDispatchGate) async throws -> [GoogleWriteProposal] {
        reads += 1
        lastReadGate = isCurrent
        if holdRead { return await withCheckedContinuation { readContinuation = $0 } }
        if failRead { throw NativeDomainClientFailure.transportUnavailable }
        return proposals
    }

    func decideGoogleWriteProposal(_ decision: GoogleWriteDecision, proposal: GoogleWriteProposal,
                                   isCurrent: @escaping NativeDispatchGate) async -> GoogleWriteDecisionResult {
        lastDecisionGate = isCurrent
        decisions.append((decision, proposal.digest))
        if holdDecision && decisions.count == 1 {
            let result = await withCheckedContinuation { decisionContinuation = $0 }
            decisionWasCancelled = Task.isCancelled
            return result
        }
        return result
    }

    func finishRead() {
        readContinuation?.resume(returning: proposals)
        readContinuation = nil
    }

    func finishDecision(_ result: GoogleWriteDecisionResult) {
        decisionContinuation?.resume(returning: result)
        decisionContinuation = nil
    }
}

private actor ProposalPollClock {
    private(set) var sleepCount = 0
    private var sleepers: [CheckedContinuation<Void, Never>] = []

    func sleep() async throws {
        sleepCount += 1
        await withCheckedContinuation { sleepers.append($0) }
        try Task.checkCancellation()
    }

    func tick() {
        guard !sleepers.isEmpty else { return }
        sleepers.removeFirst().resume()
    }
}
