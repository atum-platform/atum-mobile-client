enum GoogleProposalFixtures {
    static let agentID = "bbbbbbbb-1111-4111-8111-b11111111111"
    static let room = "!agent:example.test"
    static let eventDigest = "abd9a86ae2b043f9997c255ca6255618b353ab006a9c9489b8d11a5865d4f500"
    static let emailDigest = "7482da8524478a083582739e48c8e2fe973415120a8be29907ee50d416807266"
    static let email = #"""
        {"to":["person@example.test"],"cc":["copy@example.test"],"bcc":["blind@example.test"],
         "subject":"Cafe\u0301 / ☕","body":"line 1\nline 2\t\"test\"\\\u001f","quote":"original",
         "references":["prior"],"threadId":"thread","forwarded":{"messageId":"prior","from":"canary@example.test",
         "date":"2026-11-25","subject":"Prior","quotePreview":"orig","quoteLength":71,"truncated":true},
         "attachments":[{"filename":"notes.txt","mimeType":"text/plain","size":42}]}
        """#
    static let event = """
        {"action":"create_event","sourceId":"calendar","title":"Review","start":"2026-11-26T08:00:00+07:00",
         "end":"2026-11-26T09:00:00+07:00","location":"Room","description":"Discuss"}
        """

    static func id(_ number: Int) -> String { String(format: "aaaaaaaa-1111-4111-8111-a%011d", number) }

    static func row(_ number: Int, work: Bool = false, room: String = room, draft: String = event,
                    digest: String = eventDigest) -> String {
        let source = work ? #""source":"work","agent":null,"room":null"# : """
            "agent":"\(agentID)","room":"\(room)"
            """
        return """
            {"proposalId":"\(id(number))","operationId":"\(id(number))",\(source),"digest":"\(digest)",
             "status":"awaiting_owner","draft":\(draft),"futureMetadata":{"example":"ignored"}}
            """
    }

    static func data(_ rows: [String]) -> Data {
        Data("""
            {"proposals":[\(rows.joined(separator: ","))],"futureEnvelope":1}
            """.utf8)
    }

    static func decode(_ rows: [String]) throws -> [GoogleWriteProposal] {
        try JSONDecoder().decode(GoogleWriteProposalList.self, from: data(rows)).proposals
    }

    static func proposal(_ number: Int, work: Bool = false, digest: String = eventDigest) throws -> GoogleWriteProposal {
        try XCTUnwrap(decode([row(number, work: work, digest: digest)]).first)
    }

    static func extend(_ object: String, with fields: String) -> String {
        String(object.dropLast()) + "," + fields + "}"
    }
}

