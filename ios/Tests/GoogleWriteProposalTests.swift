enum GoogleProposalFixtures {
    static let agentID = "bbbbbbbb-1111-4111-8111-b11111111111"
    static let room = "!agent:example.test"
    static let eventDigest = "abd9a86ae2b043f9997c255ca6255618b353ab006a9c9489b8d11a5865d4f500"
    static let emailDigest = "7482da8524478a083582739e48c8e2fe973415120a8be29907ee50d416807266"
    static let email = #"""
        {"to":["person@example.test"],"cc":["copy@example.test"],"bcc":["blind@example.test"],
         "subject":"Cafe\u0301 / ☕","body":"line 1\nline 2\t\"test\"\\\u001f","quote":"original",
         "references":["prior"],"threadId":"thread","forwarded":{"messageId":"prior","from":"canary@example.test",
         "date":"2026-11-25","subject":"Prior","quotePreview":"orig","quoteLength":71,"truncated":true},
         "attachments":[{"filename":"notes.txt","mimeType":"text/plain","size":42}]}
        """#
    static let event = """
        {"action":"create_event","sourceId":"calendar","title":"Review","start":"2026-11-26T08:00:00+07:00",
         "end":"2026-11-26T09:00:00+07:00","location":"Room","description":"Discuss"}
        """

    static func id(_ number: Int) -> String { String(format: "aaaaaaaa-1111-4111-8111-a%011d", number) }

    static func row(_ number: Int, work: Bool = false, room: String = room, draft: String = event,
                    digest: String = eventDigest) -> String {
        let source = work ? #""source":"work","agent":null,"room":null"# : """
            "agent":"\(agentID)","room":"\(room)"
            """
        return """
            {"proposalId":"\(id(number))","operationId":"\(id(number))",\(source),"digest":"\(digest)",
             "status":"awaiting_owner","draft":\(draft),"futureMetadata":{"example":"ignored"}}
            """
    }

    static func data(_ rows: [String]) -> Data {
        Data("""
            {"proposals":[\(rows.joined(separator: ","))],"futureEnvelope":1}
            """.utf8)
    }

    static func decode(_ rows: [String]) throws -> [GoogleWriteProposal] {
        try JSONDecoder().decode(GoogleWriteProposalList.self, from: data(rows)).proposals
    }

    static func proposal(_ number: Int, work: Bool = false, digest: String = eventDigest) throws -> GoogleWriteProposal {
        try XCTUnwrap(decode([row(number, work: work, digest: digest)]).first)
    }

    static func extend(_ object: String, with fields: String) -> String {
        String(object.dropLast()) + "," + fields + "}"
    }
}

final class GoogleWriteProposalDecoderTests: XCTestCase {
    private typealias Fixture = GoogleProposalFixtures

    func testAssistantEmailAndWorkCalendarWithPlatformDigests() throws {
        // Digests generated by desktop's canonicalJson, including decomposed Unicode,
        // an escaped separator, quotes, and the forwarded boolean and attachment size.
        let decoded = try Fixture.decode([
            Fixture.row(1, draft: Fixture.email, digest: Fixture.emailDigest),
            Fixture.row(2, work: true)
        ])
        XCTAssertEqual(decoded.map(\.kind), [.sendEmail, .createEvent])
        XCTAssertEqual(decoded[0].source, .assistant(agentID: try NativeID(Fixture.agentID), roomID: Fixture.room))
        XCTAssertEqual(decoded[1].source, .work)
        XCTAssertEqual(decoded.map(\.digestMatchesPreview), [true, true])
        XCTAssertEqual(decoded[0].previewLines, [
            .to(["person@example.test"]), .cc(["copy@example.test"]), .bcc(["blind@example.test"]),
            .subject("Cafe\u{301} / ☕"), .forwarded(from: "canary@example.test", subject: "Prior"),
            .attachments([.init(filename: "notes.txt", mimeType: "text/plain", size: 42, sha256: nil)]),
            .reply, .body("line 1\nline 2\t\"test\"\\\u{1f}"), .quote("original"), .quoteTruncated
        ])
        XCTAssertEqual(decoded[1].previewLines, [
            .title("Review"), .start("2026-11-26T08:00:00+07:00"), .end("2026-11-26T09:00:00+07:00"),
            .location("Room"), .description("Discuss")
        ])
    }

    func testOtherSupportedActionsAndMailboxPreview() throws {
        let updateEvent = Fixture.extend(Fixture.event.replacingOccurrences(of: "create_event", with: "update_event"),
                                         with: #""eventId":"target""#)
        let createDraft = Fixture.extend(Fixture.email, with: #""action":"create_draft","sourceId":"gmail""#)
        let updateDraft = Fixture.extend(Fixture.email, with: #""action":"update_draft","sourceId":"gmail","draftId":"saved""#)
        let mailbox = #"{"action":"mailbox","sourceId":"gmail","operation":"add_labels","messageId":"target","labels":["Important"]}"#
        let label = #"{"action":"create_label","sourceId":"gmail","name":"Notes"}"#
        let decoded = try Fixture.decode([
            Fixture.row(1, draft: updateEvent, digest: "1e98aefa7093996fd2e3e986a315a0acaf3909da0dabd400134b36e45aeba107"),
            Fixture.row(2, work: true, draft: createDraft, digest: "022ddeb1b6e5e82f0c44184d5d84f8c88e9473db0318e651ae3d3c446346de67"),
            Fixture.row(3, work: true, draft: updateDraft, digest: "49b1cb60e2656595173aef8d52352033543254f0dcebe445b96e6af7ee40f77e"),
            Fixture.row(4, work: true, draft: mailbox, digest: "db8bc0b1a288a1114533c68b1bb6b453676626c2604c5e717289d6f16871841d"),
            Fixture.row(5, work: true, draft: label, digest: "b4c646533d6df2e290e2aef6fe9dfb6f1b3ee3a9e504e1927dec68866efa8e5b")
        ])
        XCTAssertEqual(decoded.map(\.kind), [.updateEvent, .createDraft, .updateDraft, .mailbox, .createLabel])
        XCTAssertTrue(decoded.allSatisfy(\.digestMatchesPreview))
        XCTAssertEqual(decoded[3].mailboxOperation, .addLabels)
        XCTAssertEqual(decoded[3].previewLines, [.mailboxTarget(conversation: false), .labels(["Important"])])
        XCTAssertEqual(decoded[4].previewLines, [.name("Notes")])
    }

    func testUnknownKindAndDraftFieldsKeepListButDoNotAuthorize() throws {
        let decoded = try Fixture.decode([
            "{}",
            Fixture.row(1, work: true, draft: #"{"action":"future_action","options":[42]}"#),
            Fixture.row(2, draft: Fixture.extend(Fixture.event, with: #""future":true"#),
                        digest: "36a664b1882ad6ff69ea340da001f8ac19cc426a87a1ac69e0cf62836bb44603"),
            Fixture.row(3),
            Fixture.row(3, work: true)
        ])
        XCTAssertEqual(decoded.map(\.kind), [.unsupported("future_action"), .createEvent, .createEvent])
        XCTAssertEqual(decoded.map(\.digestMatchesPreview), [false, false, true])
        XCTAssertTrue(decoded[0].previewLines.isEmpty)
        XCTAssertEqual(decoded[1].previewLines, decoded[2].previewLines)
    }
}

@available(macOS 14.0, *)
@MainActor final class GoogleWriteProposalStoreTests: XCTestCase {
    private typealias Fixture = GoogleProposalFixtures

    func testMountFocusPollAndAssistantHintAreScopedToVisibleConsumers() async throws {
        let clock = ProposalPollClock()
        let store = GoogleWriteProposalStore(sleep: { try await clock.sleep() })
        let api = ProposalAPI()
        store.bind(accountID: "owner-a", api: api)
        let session = store.session
        let surface = GoogleWriteProposalSurface.assistant(roomID: Fixture.room)
        store.setForeground(true)
        XCTAssertEqual(api.reads, 0)
        store.setVisible(true, for: surface, session: session)
        await until { api.reads == 1 }
        await until { await clock.sleepCount == 1 }
        await clock.tick()
        await until { api.reads == 2 }
        await until { await clock.sleepCount == 2 }
        store.hintAssistantMessage(roomID: "!other:example.test", session: session)
        store.hintAssistantMessage(roomID: Fixture.room, session: UUID())
        store.hintAssistantMessage(roomID: Fixture.room, session: session)
        await until { api.reads == 3 }
        store.setForeground(false)
        await clock.tick()
        store.hintAssistantMessage(roomID: Fixture.room, session: session)
        store.setForeground(true)
        await until { api.reads == 4 }
        await until { await clock.sleepCount == 3 }
        store.setVisible(false, for: surface, session: session)
        await clock.tick()
        // A deliberate refresh is the only new read after hiding.
        await store.refresh()
        XCTAssertEqual(api.reads, 5)
    }

    func testVisibleWorkAndAssistantSharePollAndListKeepsSourceSeparated() async throws {
        let clock = ProposalPollClock()
        let store = GoogleWriteProposalStore(sleep: { try await clock.sleep() })
        let api = ProposalAPI()
        api.proposals = [try Fixture.proposal(1), try Fixture.proposal(2, work: true)]
        store.bind(accountID: "owner-a", api: api)
        store.setVisible(true, for: .work, session: store.session)
        store.setVisible(true, for: .assistant(roomID: Fixture.room), session: store.session)
        store.setForeground(true)
        await until { store.cards.count == 2 }
        XCTAssertEqual(store.cards(for: .work).map(\.id.proposalID.rawValue), [Fixture.id(2)])
        XCTAssertEqual(store.cards(for: .assistant(roomID: Fixture.room)).map(\.id.proposalID.rawValue), [Fixture.id(1)])
        await until { await clock.sleepCount == 1 }
        await clock.tick()
        await until { api.reads == 2 }
        await until { await clock.sleepCount == 2 }
        store.setForeground(false)
        await clock.tick()
    }

    func testSwitchAndSignOutFenceInFlightReadsAndOldCardActions() async throws {
        let store = GoogleWriteProposalStore()
        let earlier = ProposalAPI()
        earlier.proposals = [try Fixture.proposal(1)]
        store.bind(accountID: "owner-a", api: earlier)
        await store.refresh()
        let oldID = try XCTUnwrap(store.cards.first?.id)

        earlier.holdRead = true
        let pending = Task { await store.refresh() }
        await until { earlier.readContinuation != nil }
        let later = ProposalAPI()
        later.proposals = [try Fixture.proposal(1, work: true)]
        store.bind(accountID: "owner-b", api: later)
        XCTAssertTrue(store.cards.isEmpty)
        await store.refresh()
        earlier.finishRead()
        await pending.value
        XCTAssertFalse(earlier.lastReadGate?() ?? true)
        XCTAssertEqual(store.cards.map(\.source), [.work])
        await store.decide(.approve, cardID: oldID)
        XCTAssertTrue(later.decisions.isEmpty)
        store.bind(accountID: nil, api: nil)
        XCTAssertNil(store.accountID)
        XCTAssertTrue(store.cards.isEmpty)
    }

    func testSingleInFlightDecisionSettlesAndRefreshesOnce() async throws {
        let store = GoogleWriteProposalStore()
        let api = ProposalAPI()
        api.proposals = [try Fixture.proposal(1)]
        api.holdDecision = true
        store.bind(accountID: "owner-a", api: api)
        await store.refresh()
        let cardID = try XCTUnwrap(store.cards.first?.id)
        let pending = Task { await store.decide(.approve, cardID: cardID) }
        await until { api.decisionContinuation != nil }
        XCTAssertEqual(store.cards.first?.state, .deciding(.approve))
        XCTAssertEqual(store.cards.first?.canDecide, false)
        await store.decide(.approve, cardID: cardID)
        await store.decide(.decline, cardID: cardID)
        XCTAssertEqual(api.decisions.map(\.1), [Fixture.eventDigest])
        api.finishDecision(.accepted)
        await pending.value
        XCTAssertEqual(api.reads, 2)
        XCTAssertEqual(store.cards.first?.state, .approved)
        await store.decide(.approve, cardID: cardID)
        XCTAssertEqual(api.decisions.count, 1)
    }

    func testDecisionAnswerAfterSignOutIsIgnoredEvenAfterSameOwnerReturns() async throws {
        let store = GoogleWriteProposalStore()
        let api = ProposalAPI()
        api.proposals = [try Fixture.proposal(1)]
        api.holdDecision = true
        store.bind(accountID: "owner-a", api: api)
        await store.refresh()
        let cardID = try XCTUnwrap(store.cards.first?.id)
        let pending = Task { await store.decide(.approve, cardID: cardID) }
        await until { api.decisionContinuation != nil }
        store.bind(accountID: nil, api: nil)
        XCTAssertFalse(api.lastDecisionGate?() ?? true)
        store.bind(accountID: "owner-a", api: api)
        await store.refresh()
        let newID = try XCTUnwrap(store.cards.first?.id)
        XCTAssertFalse(store.cards.first?.canDecide ?? true)
        await store.decide(.approve, cardID: newID)
        XCTAssertEqual(api.decisions.count, 1)
        api.finishDecision(.accepted)
        await pending.value
        XCTAssertEqual(store.cards.map(\.state), [.pending])
        XCTAssertNotEqual(newID, cardID)
        XCTAssertTrue(store.cards.first?.canDecide ?? false)
        XCTAssertEqual(api.reads, 2)
    }

    func testOutcomeMappingAndRetry() async throws {
        let cases: [(GoogleWriteDecisionResult, GoogleWriteDecision, Bool, GoogleWriteProposalState)] = [
            (.accepted, .decline, false, .declined),
            (.refused, .approve, false, .closed),
            (.refused, .approve, true, .expired),
            (.changed, .approve, true, .changed),
            (.unavailable, .approve, false, .failedRetryable)
        ]
        for (result, action, work, expected) in cases {
            let store = GoogleWriteProposalStore()
            let api = ProposalAPI()
            api.proposals = [try Fixture.proposal(1, work: work)]
            api.result = result
            store.bind(accountID: "owner-a", api: api)
            await store.refresh()
            let card = try XCTUnwrap(store.cards.first)
            await store.decide(action, cardID: card.id)
            XCTAssertEqual(store.cards.first?.state, expected)
            XCTAssertEqual(store.cards.first?.canDecide, result == .unavailable)
            if result == .unavailable {
                api.result = .accepted
                await store.decide(action, cardID: card.id)
                XCTAssertEqual(store.cards.first?.state, .approved)
                XCTAssertEqual(api.decisions.count, 2)
            }
        }
    }

    func testRefreshFailureAndListReconciliationKeepOnlySafeDecisions() async throws {
        let store = GoogleWriteProposalStore()
        let api = ProposalAPI()
        api.proposals = [try Fixture.proposal(1), try Fixture.proposal(2, work: true),
                         try Fixture.proposal(3, digest: String(repeating: "e", count: 64))]
        store.bind(accountID: "owner-a", api: api)
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.pending, .pending, .changed])
        let changed = try XCTUnwrap(store.cards.last)
        await store.decide(.approve, cardID: changed.id)
        XCTAssertTrue(api.decisions.isEmpty)

        api.failRead = true
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.pending, .pending, .changed])
        api.failRead = false
        api.proposals = [try Fixture.proposal(4)]
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.superseded, .expired, .superseded, .pending])
        api.proposals = []
        await store.refresh()
        XCTAssertEqual(store.cards.map(\.state), [.superseded, .expired, .superseded, .closed])
    }

    private func until(_ predicate: () async -> Bool, file: StaticString = #filePath, line: UInt = #line) async {
        for _ in 0..<200 {
            if await predicate() { return }
            try? await Task.sleep(for: .milliseconds(5))
        }
        XCTFail("Expected proposal activity did not occur", file: file, line: line)
    }
}

@MainActor private final class ProposalAPI: GoogleWriteProposalAPI {
    var reads = 0
    var proposals = [GoogleWriteProposal]()
    var failRead = false
    var holdRead = false
    var readContinuation: CheckedContinuation<[GoogleWriteProposal], Never>?
    var lastReadGate: NativeDispatchGate?
    var lastDecisionGate: NativeDispatchGate?
    var holdDecision = false
    var decisions: [(GoogleWriteDecision, String)] = []
    var result = GoogleWriteDecisionResult.accepted
    var decisionContinuation: CheckedContinuation<GoogleWriteDecisionResult, Never>?

    func googleWriteProposals(isCurrent: @escaping NativeDispatchGate) async throws -> [GoogleWriteProposal] {
        reads += 1
        lastReadGate = isCurrent
        if holdRead { return await withCheckedContinuation { readContinuation = $0 } }
        if failRead { throw NativeDomainClientFailure.transportUnavailable }
        return proposals
    }

    func decideGoogleWriteProposal(_ decision: GoogleWriteDecision, proposal: GoogleWriteProposal,
                                   isCurrent: @escaping NativeDispatchGate) async -> GoogleWriteDecisionResult {
        lastDecisionGate = isCurrent
        decisions.append((decision, proposal.digest))
        if holdDecision && decisions.count == 1 {
            return await withCheckedContinuation { decisionContinuation = $0 }
        }
        return result
    }

    func finishRead() {
        readContinuation?.resume(returning: proposals)
        readContinuation = nil
    }

    func finishDecision(_ result: GoogleWriteDecisionResult) {
        decisionContinuation?.resume(returning: result)
        decisionContinuation = nil
    }
}

private actor ProposalPollClock {
    private(set) var sleepCount = 0
    private var sleepers: [CheckedContinuation<Void, Never>] = []

    func sleep() async throws {
        sleepCount += 1
        await withCheckedContinuation { sleepers.append($0) }
        try Task.checkCancellation()
    }

    func tick() {
        guard !sleepers.isEmpty else { return }
        sleepers.removeFirst().resume()
    }
}
